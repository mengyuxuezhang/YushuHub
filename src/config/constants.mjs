export { SUPER_ADMIN_ID, SUPER_ADMIN_USERNAME, ADMIN_USER }

export function isSuperAdminUsername(value) {
  const username = String(value || '').trim().toLowerCase()
  return username === SUPER_ADMIN_USERNAME || username === String(ADMIN_USER || '').trim().toLowerCase()
}

export function isSuperAdminUser(user) {
  if (!user) return false
  return user.id === SUPER_ADMIN_ID || isSuperAdminUsername(user.username)
}

